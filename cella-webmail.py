def dns_resolve(domain):
    with dns_lock:
        if domain in dns_cache:
            return dns_cache[domain]
    try:
        ip = socket.getaddrinfo(domain, 443, socket.AF_INET)[0][4][0]
    except Exception:
        try:
            ip = socket.getaddrinfo(domain, 80, socket.AF_INET)[0][4][0]
        except Exception:
            ip = None
    with dns_lock:
        dns_cache[domain] = ip
    return ip


